def test_a05_provider_wait_stays_pending_after_informational_events(tmp_path):
    """I-D2 regression: informational events never close a pending wait.

    Real sequences: ``observed`` is written once at wait start; afterwards
    ``issue-report-unavailable`` / ``issue-reported`` (runner.py), runtime wait
    snapshots without an ``event`` key (runtimes/codex.py), and
    ``coordinator-delivery-failed`` (carries reporter_id, no agent_id) can all
    become the latest record while the wait is still pending.  The worst case
    ``observed -> issue-report-unavailable`` must keep provider_wait (and its
    recover_provider bindings) in pending.
    """

    repo, run_root = _make_run(tmp_path)
    _append_evidence(
        run_root,
        "provider-wait",
        [
            _provider_observed("modeling"),
            {
                "event": "issue-report-unavailable",
                "agent_id": "modeling",
                "recorded_at": "2026-09-18T12:01:00+00:00",
            },
            {
                "event": "issue-reported",
                "agent_id": "modeling",
                "issue_id": "issue-1",
                "recorded_at": "2026-09-18T12:02:00+00:00",
            },
            # Runtime wait snapshot: dict(wait) has no ``event`` key.
            {
                "agent_id": "modeling",
                "role": "modeling",
                "wait_id": "wait-modeling-1",
                "state": "waiting",
                "recorded_at": "2026-09-18T12:03:00+00:00",
            },
            {
                "event": "coordinator-delivery-failed",
                "issue_id": "issue-1",
                "reporter_id": "modeling",
                "recorded_at": "2026-09-18T12:04:00+00:00",
            },
        ],
    )
    pending = host_ops.get_pending_actions("t-run", repository_root=repo)
    assert len(pending["items"]) == 1
    wait = pending["items"][0]
    assert wait["type"] == "provider_wait"
    assert wait["agent_id"] == "modeling"
    assert wait["role"] == "modeling"
    assert wait["wait_id"] == "wait-modeling-1"
    assert wait["variant"] == "provider-unavailable"
    assert wait["available_actions"][0]["action"] == "recover_provider"


