def test_a11_handoff_and_acceptance_closure_over_real_evidence(cq_semantic_runner):
    runner = cq_semantic_runner
    run_id = runner.run.run_id
    frozen = _freeze(runner)
    # Pending: frozen pool awaiting handoff, bindings from the real freeze.
    pending = host_ops.get_pending_actions(run_id)
    (handoff_item,) = [
        entry for entry in pending["items"] if entry["type"] == "cq_handoff"
    ]
    assert handoff_item["bindings"]["freeze_id"] == BATCH_ID
    assert handoff_item["bindings"]["freeze_digest"] == frozen["snapshot_digest"]
    # Real handoff through the Runner (settled production transport, real path).
    runner.transport = _SettledTransport(runner, "completed")
    ack = runner.handle_cq_outer_input(_handoff_message(frozen))
    assert ack["ok"] is True
    pending = host_ops.get_pending_actions(run_id)
    (closure,) = [
        entry for entry in pending["items"]
        if entry["type"] == "cq_acceptance_closure"
    ]
    assert closure["status"] == "acceptance_pending"
    assert closure["bindings"]["acceptance_attempt_id"] == "attempt-0001"
    report_directory = closure["bindings"]["report_directory"]
    assert report_directory == f"acceptance-v3/reports/{BATCH_ID}/attempt-0001"
    # A11-5: no report yet -> typed local rejection, no FIFO write, no ledger.
    with pytest.raises(host_ops.HostOpError) as missing:
        host_ops.complete_cq_acceptance(run_id, request_id="req-acc")
    assert missing.value.code == "cq_acceptance_report_mismatch"
    assert not (runner.run.root / "control" / "host-requests.jsonl").exists()
    # The real pure builder writes the attempt report, then the op layer
    # assembles the completion envelope from it.
    report_bytes, report_digest = _write_report(
        runner, frozen, verdicts=[_verdict_entry("model-recall-insufficient")]
    )
    fifo = OuterInputFifo(runner.run.root / "control" / "outer-input.fifo")
    fifo.open()
    try:
        result = host_ops.complete_cq_acceptance(run_id, request_id="req-acc")
        assert result["status"] == "submitted"
        envelope = _pop_fifo_line(fifo)
        assert set(envelope) == set(CQ_ACCEPTANCE_COMPLETE_FIELDS) | {"request_id"}
        assert envelope["report_digest"] == report_digest
        assert envelope["cq_verdict"] == "partial"  # judged but not full pass
        assert envelope["batch_id"] == BATCH_ID
        assert envelope["acceptance_attempt_id"] == "attempt-0001"
        # A11-6: the Runner re-verifies the same envelope with its own pure
        # helpers and accepts it (tool and Runner share the contract).
        runner_envelope = {key: value for key, value in envelope.items() if key != "request_id"}
        completion = runner.handle_cq_outer_input(runner_envelope)
        assert completion["ok"] is True
        assert completion["cq_verdict"] == "partial"
        assert completion["report_digest"] == report_digest
    finally:
        fifo.close()


