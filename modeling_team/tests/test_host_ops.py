def _two_source_events(run_root: Path) -> None:
    _append_evidence(
        run_root,
        "alpha.jsonl".removesuffix(".jsonl"),
        [
            {"n": 1, "recorded_at": "2026-09-18T10:00:01+00:00"},
            {"n": 2, "recorded_at": "2026-09-18T10:00:03+00:00"},
            {"n": 3, "recorded_at": "2026-09-18T10:00:05+00:00"},
        ],
    )
    _append_evidence(
        run_root,
        "beta",
        [
            {"n": 10, "recorded_at": "2026-09-18T10:00:02+00:00"},
            {"n": 11, "recorded_at": "2026-09-18T10:00:04+00:00"},
        ],
    )


def test_a02_1_pagination_without_dup_or_loss(tmp_path):
    repo, run_root = _make_run(tmp_path)
    _two_source_events(run_root)
    seen: list[tuple[str, int]] = []
    cursor = None
    for _ in range(5):
        page = host_ops.get_run_events(
            "t-run", repository_root=repo, cursor=cursor, limit=2
        )
        for event in page["events"]:
            seen.append((event["source"], event["data"]["n"]))
        cursor = page["next_cursor"]
        if not page["has_more"]:
            break
    assert seen == [
        ("alpha.jsonl", 1),
        ("beta.jsonl", 10),
        ("alpha.jsonl", 2),
        ("beta.jsonl", 11),
        ("alpha.jsonl", 3),
    ]


def _cursor_payload(cursor: str) -> dict:
    return json.loads(base64.urlsafe_b64decode(cursor))


def _drain_events(repo: Path, limit: int, max_pages: int = 500):
    """Drive get_run_events to exhaustion (I2-D1 regressions).

    Returns ``(events, final_cursor)`` and asserts the two pagination
    invariants: no page after a ``has_more=True`` page is ever empty, and the
    final cursor is a true end state (one extra read delivers nothing).
    """

    events: list[dict] = []
    cursor = None
    for _ in range(max_pages):
        page = host_ops.get_run_events(
            "t-run", repository_root=repo, cursor=cursor, limit=limit
        )
        assert page["events"], "empty page delivered while pagination continued"
        events.extend(page["events"])
        cursor = page["next_cursor"]
        if not page["has_more"]:
            break
    else:
        raise AssertionError(f"pagination did not terminate within {max_pages} pages")
    drained = host_ops.get_run_events(
        "t-run", repository_root=repo, cursor=cursor, limit=limit
    )
    assert drained["events"] == []
    assert drained["has_more"] is False
    return events, cursor


def _line_starts(lines: list[str]) -> dict[str, int]:
    starts: dict[str, int] = {}
    offset = 0
    for line in lines:
        starts[line] = offset
        offset += len(line.encode("utf-8"))
    return starts


def test_a02_1a_same_source_pagination_unequal_line_lengths(tmp_path):
    """I-D1 regression: same-source pages must accumulate offsets, not restart.

    The M-layer twin-source test always took one line per source per page, so a
    per-line (non-cumulative) offset still produced plausible pages.  Here one
    source serves several lines of deliberately unequal length per page; a
    non-cumulative offset would resume inside an already delivered line and
    fabricate corrupt records or redeliver lines.
    """

    lines = [
        '{"n": 1, "recorded_at": "2026-09-18T10:00:01+00:00"}\n',
        '{"n": 2, "pad": "' + ("y" * 220) + '", "recorded_at": "2026-09-18T10:00:02+00:00"}\n',
        '{"n": 3, "recorded_at": "2026-09-18T10:00:03+00:00"}\n',
        '{"n": 4, "pad": "' + ("z" * 180) + '", "recorded_at": "2026-09-18T10:00:04+00:00"}\n',
        '{"n": 5, "recorded_at": "2026-09-18T10:00:05+00:00"}\n',
    ]
    repo, run_root = _make_run(tmp_path)
    path = run_root / "evidence" / "alpha.jsonl"
    path.write_text("".join(lines), encoding="utf-8")
    starts: list[int] = []
    offset = 0
    for line in lines:
        starts.append(offset)
        offset += len(line.encode("utf-8"))

    seen: list[int] = []
    byte_offsets: list[int] = []
    cursor = None
    for _ in range(6):
        page = host_ops.get_run_events(
            "t-run", repository_root=repo, cursor=cursor, limit=2
        )
        for event in page["events"]:
            seen.append(event["data"]["n"])
            byte_offsets.append(event["byte_offset"])
        cursor = page["next_cursor"]
        if not page["has_more"]:
            break
    assert seen == [1, 2, 3, 4, 5]
    assert byte_offsets == starts
    assert _cursor_payload(cursor)["offsets"]["alpha.jsonl"] == path.stat().st_size


