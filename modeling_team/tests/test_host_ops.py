# --- tmp run-root helpers ------------------------------------------------------


def _make_run(tmp_path: Path, run_id: str = "t-run") -> tuple[Path, Path]:
    repo = tmp_path / "repo"
    run_root = repo / "workspaces" / "modeling-runs" / run_id
    (run_root / "evidence").mkdir(parents=True)
    (run_root / "control").mkdir(parents=True)
    (run_root / "state.json").write_text(
        json.dumps({"state": "RUNNING", "run_id": run_id}), encoding="utf-8"
    )
    return repo, run_root


def _set_state(run_root: Path, state: str, **extra) -> None:
    payload = {"state": state, "run_id": run_root.name, **extra}
    (run_root / "state.json").write_text(json.dumps(payload), encoding="utf-8")


def _append_evidence(run_root: Path, name: str, records: list[dict]) -> None:
    path = run_root / "evidence" / f"{name}.jsonl"
    with path.open("a", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, ensure_ascii=False) + "\n")


def _open_fifo(run_root: Path) -> OuterInputFifo:
    fifo = OuterInputFifo(run_root / "control" / "outer-input.fifo")
    fifo.open()
    return fifo


def _pop_fifo_line(fifo: OuterInputFifo) -> dict:
    fifo.read_ready()
    line = fifo.pop_line()
    assert line is not None
    return json.loads(line)


