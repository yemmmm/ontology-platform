    expected = {
        ("alpha.jsonl", 0),
        ("alpha.jsonl", len(line0.encode("utf-8"))),
        ("alpha.jsonl", len(line0.encode("utf-8")) + len(line1.encode("utf-8"))),
        ("beta.jsonl", 0),
        ("beta.jsonl", len(beta0.encode("utf-8"))),
    }
    assert delivered == expected
    assert sorted(
        {event["data"]["n"] for event in events if event["source"] == "alpha.jsonl"}
    ) == [0, 1, 2]
    offsets = _cursor_payload(cursor)["offsets"]
    assert offsets["alpha.jsonl"] == alpha_path.stat().st_size
    assert offsets["beta.jsonl"] == beta_path.stat().st_size


