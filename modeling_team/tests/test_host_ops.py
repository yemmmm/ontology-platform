def test_a02_17_seeded_random_multisource_pagination_property(tmp_path, monkeypatch):
    """Round 3 property test: randomized multi-source fixtures drained at a
    random limit must satisfy the pagination contract (I3-D1).

    Fixtures interleave normal lines with random (often out-of-file-order)
    stamps, corrupt lines, oversized lines, and late-appended earlier-stamped
    lines added after a first truncated page.  Asserts: bounded termination,
    complete delivery union by (source, byte_offset), corrupt/truncated
    placeholders delivered exactly once, duplicates only among normal events,
    no empty page after has_more=True, and final cursors at EOF.  Seed is
    fixed; failures reproduce deterministically.
    """

    monkeypatch.setattr(host_ops, "EVENT_LINE_BYTE_CAP", 512)
    rng = random.Random(20260918)
    for iteration in range(24):
        repo, run_root = _make_run(tmp_path / f"case-{iteration}")
        sources = {
            f"src{index}": [] for index in range(rng.randint(2, 4))
        }
        counter = 0

        def _line() -> str:
            nonlocal counter
            kind = rng.random()
            counter += 1
            if kind < 0.15:
                return "{oops-%d\n" % counter
            if kind < 0.30:
                return (
                    json.dumps(
                        {
                            "n": counter,
                            "pad": "x" * rng.randint(600, 900),
                            "recorded_at": "2026-09-18T10:%02d:%02d+00:00"
                            % (rng.randint(0, 9), rng.randint(0, 59)),
                        }
                    )
                    + "\n"
                )
            return (
                json.dumps(
                    {
                        "n": counter,
                        "recorded_at": "2026-09-18T10:%02d:%02d+00:00"
                        % (rng.randint(0, 9), rng.randint(0, 59)),
                    }
                )
                + "\n"
            )

        for lines in sources.values():
            lines.extend(_line() for _ in range(rng.randint(0, 10)))
        for name, lines in sources.items():
            (run_root / "evidence" / f"{name}.jsonl").write_text(
                "".join(lines), encoding="utf-8"
            )
        limit = rng.randint(1, 4)

        # First truncated page, then late appends (some with earlier stamps).
        page1 = host_ops.get_run_events("t-run", repository_root=repo, limit=limit)
        assert page1["events"], "first page empty with populated sources"
        for name, lines in sources.items():
            if rng.random() < 0.6:
                extra = [_line() for _ in range(rng.randint(1, 3))]
                lines.extend(extra)
                with (run_root / "evidence" / f"{name}.jsonl").open(
                    "a", encoding="utf-8"
                ) as handle:
                    handle.write("".join(extra))

        events = list(page1["events"])
        cursor = page1["next_cursor"]
        total_lines = sum(len(lines) for lines in sources.values())
        max_pages = 2 * total_lines + len(sources) + 4
        expect_nonempty = page1["has_more"] or any(
            (run_root / "evidence" / f"{name}.jsonl").stat().st_size
            > _cursor_payload(cursor)["offsets"].get(f"{name}.jsonl", 0)
            for name in sources
        )
        for _ in range(max_pages):
            page = host_ops.get_run_events(
                "t-run", repository_root=repo, cursor=cursor, limit=limit
            )
            if expect_nonempty:
                assert page["events"], (
                    "empty page delivered after a page with has_more=True"
                )
            events.extend(page["events"])
            cursor = page["next_cursor"]
            expect_nonempty = page["has_more"]
            if not page["has_more"]:
                break
        else:
            raise AssertionError(
                f"iteration {iteration}: no convergence within {max_pages} pages"
            )

        expected = {
            (f"{name}.jsonl", start)
            for name, lines in sources.items()
            for start in _line_starts(lines).values()
        }
        delivered = {(event["source"], event["byte_offset"]) for event in events}
        assert delivered == expected, f"iteration {iteration}: union mismatch"
        placeholders = [
            event for event in events if event.get("corrupt") or event.get("truncated")
        ]
        expected_placeholders = {
            (f"{name}.jsonl", _line_starts(lines)[line])
            for name, lines in sources.items()
            for line in lines
            if line.startswith("{oops-") or len(line.encode("utf-8")) > 512
        }
        assert sorted((e["source"], e["byte_offset"]) for e in placeholders) == sorted(
            expected_placeholders
        ), f"iteration {iteration}: placeholder delivery mismatch"
        seen: set[tuple[str, int]] = set()
        for event in events:
            key = (event["source"], event["byte_offset"])
            if key in seen:
                assert not (
                    event.get("corrupt") or event.get("truncated")
                ), "placeholder re-delivered"
            seen.add(key)
        offsets = _cursor_payload(cursor)["offsets"]
        for name, lines in sources.items():
            path = run_root / "evidence" / f"{name}.jsonl"
            assert offsets[f"{name}.jsonl"] == path.stat().st_size, (
                f"iteration {iteration}: source {name} not drained to EOF"
            )


def test_a02_13_late_append_second_source_and_truncation(tmp_path):
    """I2-D1 regression, tester shape 3 (design §6 flagship): a late-appended
    earlier-stamped line plus a second source plus page truncation.

    P1=[0,100]; then alpha gains line 2 (stamp 02, appended after line 1's
    stamp 09) and beta gains a line.  P2 delivers the appended line; the old
    max-delivered-end advance then parked alpha at EOF and line 1 was
    permanently lost with an empty P3.  The cursor must park at line 1's start
    so every line lands in the delivery union exactly once.
    """

    repo, run_root = _make_run(tmp_path)
    alpha_path = run_root / "evidence" / "alpha.jsonl"
    beta_path = run_root / "evidence" / "beta.jsonl"
    line0 = json.dumps({"n": 0, "recorded_at": "2026-09-18T10:00:01+00:00"}) + "\n"
    line1 = json.dumps({"n": 1, "recorded_at": "2026-09-18T10:00:09+00:00"}) + "\n"
    line2 = json.dumps({"n": 2, "recorded_at": "2026-09-18T10:00:02+00:00"}) + "\n"
    beta0 = json.dumps({"n": 100, "recorded_at": "2026-09-18T10:00:03+00:00"}) + "\n"
    beta1 = json.dumps({"n": 101, "recorded_at": "2026-09-18T10:00:04+00:00"}) + "\n"
    alpha_path.write_text(line0 + line1, encoding="utf-8")
    beta_path.write_text(beta0, encoding="utf-8")

    page1 = host_ops.get_run_events("t-run", repository_root=repo, limit=2)
    assert [event["data"]["n"] for event in page1["events"]] == [0, 100]
    assert page1["has_more"] is True
    # Late append AFTER the first truncated page: line 2 carries an earlier
    # stamp than line 1 and sits physically after it.
    alpha_path.write_text(line0 + line1 + line2, encoding="utf-8")
    beta_path.write_text(beta0 + beta1, encoding="utf-8")

    events, cursor = _drain_events(repo, limit=2)
